async page => {
 const checks=[], errors=[];
 page.on('pageerror', e=>errors.push(String(e)));
 page.on('console', m=>{if(m.type()==='error')errors.push(m.text());});
 const state=()=>page.evaluate(()=>JSON.parse(window.firetruckTouch.telemetry));
 const check=(ok,label)=>{if(!ok)throw Error(label);checks.push(label);};
 const wait=async predicate=>page.waitForFunction(predicate,null,{timeout:60000});
 const command=async(action,args={})=>{
  await page.evaluate(({action,args})=>{Object.assign(window.firetruckQA,args,{action});window.firetruckQA.sequence++;},{action,args});
  await page.waitForTimeout(400);
 };
 await page.setViewportSize({width:1280,height:800});
 await page.waitForFunction(()=>document.querySelector('#progress').getAttribute('aria-valuenow')==='100',null,{timeout:60000});
 await page.getByRole('button',{name:'Start',exact:true}).click();
 await wait(()=>!JSON.parse(window.firetruckTouch.telemetry).loading);
 await page.keyboard.press('Space');
 await wait(()=>JSON.parse(window.firetruckTouch.telemetry).phone_waiting && JSON.parse(window.firetruckTouch.telemetry).pickup_ready);
 await page.screenshot({path:'output/playwright/phone-pickup-arrow.png'});
 check((await state()).truck_frozen && !(await state()).talking,'The opening call waits for pickup with truck control held');
 await page.keyboard.press('Space');
 await wait(()=>JSON.parse(window.firetruckTouch.telemetry).interrupting);
 await page.screenshot({path:'output/playwright/interrupting-dispatch.png'});
 check((await state()).speaker==='DISPATCH','Pickup opens the interrupting dispatch message');
 await page.keyboard.down('w');
 await page.waitForTimeout(600);
 check(!(await state()).talking && (await state()).speed<.2,'Any button dismisses the call without letting its held input drive');
 await page.keyboard.up('w');
 await command('visit_race');
 await command('pose',{x:-37,z:2});
 await page.keyboard.press('Space');
 await wait(()=>JSON.parse(window.firetruckTouch.telemetry).challenge.offering);
 await page.waitForTimeout(1500);
 await page.screenshot({path:'output/playwright/quinn-challenge-offer-desktop.png'});
 await page.keyboard.press('ArrowRight');
 check((await state()).challenge.offering,'Right changes the answer without confirming it');
 await page.keyboard.press('Shift');
 await page.waitForTimeout(500);
 check(!(await state()).challenge.staging && !(await state()).interrupting,'A non-directional button confirms No and preserves exploration');
 await page.keyboard.press('Space');
 await command('pose',{x:0,z:4});
 await command('pose',{x:-37,z:2});
 await page.keyboard.press('Space');
 await wait(()=>JSON.parse(window.firetruckTouch.telemetry).challenge.offering);
 await page.keyboard.press('ArrowLeft');
 await page.keyboard.press('Enter');
 await wait(()=>JSON.parse(window.firetruckTouch.telemetry).challenge.countdown==='2');
 await page.screenshot({path:'output/playwright/quinn-upgraded-car-countdown.png'});
 check((await state()).truck_frozen && (await state()).challenge.rival_collision===2,'Countdown stages the detailed physical rival beside the truck');
 await wait(()=>JSON.parse(window.firetruckTouch.telemetry).challenge.active);
 await command('drive_race');
 await page.waitForTimeout(5500);
 await page.screenshot({path:'output/playwright/quinn-physics-race.png'});
 check((await state()).lap_running,'Real truck driving crosses START and races the physical opponent');
 await wait(()=>JSON.parse(window.firetruckTouch.telemetry).challenge.result);
 await command('stop_race_drive');
 await wait(()=>JSON.parse(window.firetruckTouch.telemetry).speaker==='QUINN' && JSON.parse(window.firetruckTouch.telemetry).interrupting);
 const loss=await state();
 check(loss.challenge.rival_finish>0 && !loss.challenge.ceremony_won && loss.challenge.rival_collision===0 && loss.dialogue_text.includes('better luck next time'),'The faster rival wins, vanishes without a collider, and returns us to Quinn at the podium');
 await page.screenshot({path:'output/playwright/quinn-podium-loss.png'});
 await page.keyboard.press('Enter');
 await wait(()=>!JSON.parse(window.firetruckTouch.telemetry).challenge.result);
 await command('pose',{x:0,z:4});
 await command('pose',{x:-37,z:2});
 await page.keyboard.press('Space');
 await wait(()=>JSON.parse(window.firetruckTouch.telemetry).challenge.offering);
 await page.keyboard.press('Enter');
 await wait(()=>JSON.parse(window.firetruckTouch.telemetry).challenge.active);
 await command('challenge_finish',{value:1});
 await wait(()=>JSON.parse(window.firetruckTouch.telemetry).speaker==='REPORTER');
 await page.waitForTimeout(1700);
 const win=await state();
 check(win.challenge.ceremony_won && win.truck_frozen && win.dialogue_text.includes('new champion of the Motorway Race Club'),'Winning stages the filmed ceremony and the requested championship announcement');
 await page.screenshot({path:'output/playwright/fire-truck-champion-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(1800);
 await page.screenshot({path:'output/playwright/fire-truck-champion-portrait.png'});
 const portrait=await state(), r=portrait.dialogue_rect;
 check(r[0]>=0 && r[0]+r[2]<=portrait.logical_view[0]+1 && r[1]+r[3]<=portrait.logical_view[1]+1,'Ceremony dialogue fits a portrait screen');
 await page.keyboard.press('Enter');
 await wait(()=>!JSON.parse(window.firetruckTouch.telemetry).challenge.result);
 check(!(await state()).truck_frozen && !(await state()).challenge.rival_collision,'Dismissing the ceremony restores driving with no hidden rival collider');
 check(errors.length===0,'No browser engine or console errors');
 return {checks,loss:loss.challenge,win:win.challenge,errors};
}
