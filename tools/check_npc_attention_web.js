async page => {
 const errors=[],checks=[];
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 page.on('pageerror',e=>errors.push(String(e)));
 const state=()=>page.evaluate(()=>JSON.parse(window.firetruckTouch.telemetry));
 const wait=p=>page.waitForFunction(p,null,{timeout:60000});
 const check=(ok,label)=>{if(!ok)throw Error(label);checks.push(label);};
 const cmd=async(action,args={})=>{await page.evaluate(({action,args})=>{Object.assign(window.firetruckQA,args,{action});window.firetruckQA.sequence++},{action,args});await page.waitForTimeout(450);};
 await page.setViewportSize({width:1280,height:800});
 await page.goto('http://localhost:8064/?qa=travel&review=npc-attention-final');
 await wait(()=>document.querySelector('#progress').getAttribute('aria-valuenow')==='100');
 await page.getByRole('button',{name:'Start',exact:true}).click();
 await wait(()=>JSON.parse(window.firetruckTouch.telemetry).intro);
 await page.keyboard.press('Space');
 await wait(()=>JSON.parse(window.firetruckTouch.telemetry).phone_waiting&&JSON.parse(window.firetruckTouch.telemetry).pickup_ready);
 await page.keyboard.press('Space');await page.waitForTimeout(250);await page.keyboard.press('Enter');
 await cmd('pose',{x:12,z:-1});
 await wait(()=>JSON.parse(window.firetruckTouch.telemetry).npc_attention.visible);
 await page.waitForTimeout(1200);
 const help=await state();
 check(help.npc_attention.index===0&&!help.talking&&!help.truck_frozen&&help.conversation_blend>.9,'Maya shows help and close framing without interrupting control');
 await page.screenshot({path:'output/playwright/npc-help-desktop.png'});
 await page.keyboard.down('w');await page.waitForTimeout(800);await page.keyboard.up('w');
 const moving=await state();
 check(!moving.talking&&!moving.truck_frozen&&Math.hypot(moving.truck_position[0]-help.truck_position[0],moving.truck_position[1]-help.truck_position[1])>.5,'Driving continues while the help prompt is visible');
 await cmd('pose',{x:12,z:-1});
 await page.keyboard.press('Space');await wait(()=>JSON.parse(window.firetruckTouch.telemetry).interrupting);
 check((await state()).truck_frozen,'Space explicitly opens the blocking mission conversation');
 await page.keyboard.press('Enter');await cmd('pose',{x:0,z:12});
 check(!(await state()).npc_attention.visible,'Leaving dismisses the attention prompt');
 await page.setViewportSize({width:390,height:844});
 await cmd('pose',{x:-49,z:-1});await wait(()=>JSON.parse(window.firetruckTouch.telemetry).npc_attention.visible);
 await page.waitForTimeout(1200);
 const portrait=await state(),r=portrait.npc_attention.rect;
 check(r[0]>=0&&r[1]>=0&&r[0]+r[2]<=portrait.logical_view[0]&&r[1]+r[3]<=portrait.logical_view[1],'Help bubble stays inside a portrait viewport');
 await page.screenshot({path:'output/playwright/npc-help-portrait.png'});
 const canvas=await page.locator('#canvas').boundingBox();
 await page.mouse.click(canvas.x+(r[0]+r[2]/2)*canvas.width/portrait.logical_view[0],canvas.y+(r[1]+r[3]/2)*canvas.height/portrait.logical_view[1]);
 await wait(()=>JSON.parse(window.firetruckTouch.telemetry).interrupting);
 check((await state()).speaker==='JUNE','Clicking the help bubble opens its NPC briefing');
 await page.keyboard.press('Enter');await cmd('visit_race');await cmd('pose',{x:-37,z:2});
 await wait(()=>JSON.parse(window.firetruckTouch.telemetry).npc_attention.visible);
 check(!(await state()).challenge.offering&&!(await state()).truck_frozen,'Quinn waits for explicit talk before offering the race');
 await page.screenshot({path:'output/playwright/quinn-attention-portrait.png'});
 await page.keyboard.press('Space');await wait(()=>JSON.parse(window.firetruckTouch.telemetry).challenge.offering);
 check((await state()).interrupting,'The race choice opens after explicit talk');
 await page.keyboard.press('ArrowRight');await page.keyboard.press('Enter');
 check(errors.length===0,'The exported game has no console or engine errors');
 return {checks,errors};
}
